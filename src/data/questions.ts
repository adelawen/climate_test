const stems = [
  (p: string) => p,
  (p: string) => `第一次複習時，關於「${p.replace(/[？?]$/,'')}」的判斷，何者正確？`,
  (p: string) => `依第一冊內容與環境部四選一題型，下列針對「${p.replace(/[？?]$/,'')}」的回答何者最佳？`,
]

function rotate<T>(items: T[], by: number): T[] {
  return items.map((_, index) => items[(index + by) % items.length])
}

export const questions: Question[] = concepts.flatMap((concept, conceptIndex) =>
  [0, 1, 2].map((variant) => {
    const targetAnswer = (conceptIndex * 3 + variant) % 4
    const shift = (concept.answer - targetAnswer + 4) % 4
    const options = rotate(concept.options, shift)
    const answer = (concept.answer - shift + 4) % 4
    const notes = concept.options.map((_, index) => index === concept.answer ? concept.explanation : concept.wrongNotes[index])
    const explanations = rotate(notes, shift)
    const kind: QuestionKind = conceptIndex < 30 ? '教材重點' : conceptIndex < 35 ? '官方題型' : '情境整合'
    const difficulty: Difficulty = variant === 0 ? '基礎' : variant === 1 ? '理解' : '情境'
    return {
      id: `B1-${String(conceptIndex * 3 + variant + 1).padStart(3, '0')}`,
      bookId: 1,
      chapter: concept.chapter,
      topic: concept.topic,
      kind,
      difficulty,
      stem: stems[variant](concept.prompt),
      options,
      answer,
      explanations,
      explanation: concept.explanation,
      memoryHook: concept.memoryHook,
      pages: concept.pages,
      handwritten: Boolean(concept.handwritten),
      mutable: Boolean(concept.mutable),
      checkedOn: '2026-09-12',
    }
  })
)
